// Função para abrir/fechar o menu de idiomas
function toggleLanguageMenu() {
    const menu = document.getElementById('languageMenu');
    if (menu) {
        menu.classList.toggle('open');
    }
}

// Função para trocar o idioma
function setLanguage(lang) {
    // Salva a preferência
    localStorage.setItem('voyage-language', lang);

    // Dispara o evento para o noticia.js re-carregar a notícia
    window.dispatchEvent(new Event('languageChanged'));

    // Traduz todos os elementos com data-i18n
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang][key]) {
            element.innerHTML = translations[lang][key];
        }
    });

    // Atualiza o botão de idioma
    const langLabel = document.getElementById('languageLabel');
    if (langLabel) {
        langLabel.textContent = lang.toUpperCase();
    }

    // Atualiza o botão ativo no menu
    document.querySelectorAll('.language-menu button').forEach(btn => {
        btn.classList.remove('active');
        if (btn.getAttribute('onclick').includes(`'${lang}'`)) {
            btn.classList.add('active');
        }
    });

    // Fecha o menu após selecionar
    const menu = document.getElementById('languageMenu');
    if (menu) {
        menu.classList.remove('open');
    }

    // Mostra mensagem personalizada
    const langToast = document.getElementById('languageToast');
    if (langToast) {
        const messages = {
            'pt': 'Idioma alterado para Português',
            'en': 'Language changed to English',
            'es': 'Idioma cambiado a Español'
        };
        langToast.textContent = messages[lang];
        langToast.classList.add('show');
        setTimeout(() => {
            langToast.classList.remove('show');
        }, 3000);
    }
}

// Inicializa o idioma salvo
function initLanguage() {
    const savedLang = localStorage.getItem('voyage-language') || 'pt';
    setLanguage(savedLang);
}

// Fecha o menu ao clicar fora
document.addEventListener('click', function(event) {
    const selector = document.querySelector('.language-selector');
    const menu = document.getElementById('languageMenu');
    if (selector && menu && !selector.contains(event.target)) {
        menu.classList.remove('open');
    }
});

// Inicializa ao carregar a página
document.addEventListener('DOMContentLoaded', initLanguage);